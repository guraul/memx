import { readFileSync, writeFileSync, renameSync, mkdirSync, existsSync, readdirSync, unlinkSync } from "fs";
import { join, basename } from "path";
import { homedir } from "os";
import type { UserMdDoc, UserMdSection, StyleProposal } from "../types";
import { CATEGORY_HEADERS, HEADER_TO_CATEGORY, CATEGORIES, type Category } from "../types";
import { trimBlankLines, trimTrailingBlankLines } from "./markdown-lines";

const ENTRY_REGEX = /^- (~~)?\[(\d{4}-\d{2}-\d{2})\]\s+(.+?)(~~)?(?:\s+\(Deprecated:.*\))?$/;

/** 由 serializeUserMd 每次重建的头部：解析时丢弃，否则每轮往返都会重复堆积 */
const GENERATED_HEADER = "# User Profile & Style";
const GENERATED_META_REGEX = /^> Auto-generated by opencode-memx\. Last updated: /;

export function getUserMdPath(): string {
  return join(homedir(), ".opencode", "USER.md");
}

function ensureDir(): void {
  const dir = join(homedir(), ".opencode");
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
  }
}

export function readUserMd(): string {
  const path = getUserMdPath();
  if (!existsSync(path)) {
    return "";
  }
  return readFileSync(path, "utf-8");
}

export function writeUserMd(content: string): void {
  ensureDir();
  const path = getUserMdPath();

  if (existsSync(path)) {
    backupUserMd();
    cleanupOldBackups(5);
  }

  const tmpPath = `${path}.tmp.${Date.now()}`;
  writeFileSync(tmpPath, content, "utf-8");
  renameSync(tmpPath, path);
}

/** 是否是我们自己生成的头部行（序列化时总会重建，解析时直接丢掉） */
function isGeneratedHeaderLine(line: string): boolean {
  return line === GENERATED_HEADER || GENERATED_META_REGEX.test(line);
}

/**
 * 解析 USER.md。受管集合 = 四个固定分类小节 + 其中的 `- [YYYY-MM-DD]` 条目；
 * 其余一切（用户自写的一级标题、散文、未知 ## 小节、小节里的非条目行、尾部内容）
 * 一律当作非受管内容原样带走，写回时不得丢失。
 */
export function parseUserMd(content: string): UserMdDoc {
  if (!content.trim()) {
    return {
      preamble: [],
      sections: CATEGORIES.map((cat) => ({
        header: CATEGORY_HEADERS[cat],
        category: cat,
        lines: [],
      })),
    };
  }

  const lines = content.split("\n");
  const preamble: string[] = [];
  const sections: UserMdSection[] = [];
  let current: UserMdSection | null = null;
  // 最近一个受管小节：受管区域内的非受管行（含未知 ## 小节）挂到它身上，
  // 这样未知小节不会跑到文件顶部被重排。
  let lastManaged: UserMdSection | null = null;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!;
    const headerMatch = line.match(/^## (.+)$/);

    if (headerMatch) {
      const header = headerMatch[1]!;
      const cat = HEADER_TO_CATEGORY[header];
      if (cat) {
        current = { header, category: cat, lines: [] };
        sections.push(current);
        lastManaged = current;
        continue;
      }
      // 未识别 ## 小节：整段按非受管内容保留，其后的条目行也不再归属上一个受管小节
      current = null;
    }

    const entryMatch = current ? line.match(ENTRY_REGEX) : null;
    if (entryMatch && current) {
      const date = entryMatch[2] ?? "";
      const text = entryMatch[3] ?? "";
      current.lines.push({
        raw: line,
        date,
        text,
        deprecated: !!entryMatch[1],
        lineNumber: i + 1,
      });
      continue;
    }

    if (current || lastManaged) {
      const owner = current ?? lastManaged!;
      owner.extras = [...(owner.extras ?? []), line];
    } else {
      preamble.push(line);
    }
  }

  return {
    // 我们自己生成的头部不带走（序列化会重建），否则往返会重复
    preamble: trimBlankLines(preamble.filter((l) => !isGeneratedHeaderLine(l))),
    sections,
  };
}

export function serializeUserMd(doc: UserMdDoc, lastUpdated?: string): string {
  const date = lastUpdated ?? new Date().toISOString().split("T")[0] ?? "";
  const result: string[] = [];

  // 非受管的前言排在生成头部之前，位置与原文一致
  if (doc.preamble.length > 0) {
    result.push(...doc.preamble, "");
  }

  result.push(GENERATED_HEADER, "", `> Auto-generated by opencode-memx. Last updated: ${date}`, "");

  for (const section of doc.sections) {
    const extras = trimTrailingBlankLines(section.extras ?? []);
    if (section.lines.length === 0 && extras.length === 0) continue;
    result.push(`## ${section.header}`);
    for (const entry of section.lines) {
      result.push(entry.raw);
    }
    result.push(...extras);
    result.push("");
  }

  return result.join("\n");
}

export function backupUserMd(): string | null {
  const path = getUserMdPath();
  if (!existsSync(path)) return null;
  const bakPath = `${path}.bak.${Date.now()}`;
  const content = readFileSync(path, "utf-8");
  writeFileSync(bakPath, content, "utf-8");
  return bakPath;
}

export function cleanupOldBackups(maxKeep = 5): void {
  const dir = join(homedir(), ".opencode");
  if (!existsSync(dir)) return;

  const prefix = `${basename(getUserMdPath())}.bak.`;
  const backups = readdirSync(dir)
    .filter((f) => f.startsWith(prefix))
    .map((f) => join(dir, f))
    .sort()
    .reverse();

  for (const old of backups.slice(maxKeep)) {
    try {
      unlinkSync(old);
    } catch {
      // ignore
    }
  }
}

export function isOverLimit(content: string, limit = 200): boolean {
  return content.split("\n").length > limit;
}

export function applyProposal(proposal: StyleProposal, content: string): string {
  const doc = parseUserMd(content);
  const sections = doc.sections;
  const today = new Date().toISOString().split("T")[0] ?? "";
  const cat = proposal.category as Category;
  const header = CATEGORY_HEADERS[cat];

  let targetSection = sections.find((s) => s.category === cat);
  if (!targetSection) {
    targetSection = { header, category: cat, lines: [] };
    sections.push(targetSection);
  }

  const newRaw = `- [${today}] ${proposal.content}`;

  switch (proposal.action) {
    case "append": {
      targetSection.lines.push({
        raw: newRaw,
        date: today,
        text: proposal.content,
        deprecated: false,
        lineNumber: 0,
      });
      break;
    }
    case "update": {
      let found = false;
      for (const section of sections) {
        const idx = section.lines.findIndex(
          (e) => proposal.target_line != null && e.lineNumber === proposal.target_line,
        );
        if (idx !== -1) {
          section.lines[idx] = {
            raw: newRaw,
            date: today,
            text: proposal.content,
            deprecated: false,
            lineNumber: 0,
          };
          found = true;
          break;
        }
      }
      if (!found) {
        targetSection.lines.push({
          raw: newRaw,
          date: today,
          text: proposal.content,
          deprecated: false,
          lineNumber: 0,
        });
      }
      break;
    }
    case "deprecate": {
      for (const section of sections) {
        const target = section.lines.find(
          (e) => proposal.target_line != null && e.lineNumber === proposal.target_line,
        );
        if (target && !target.deprecated) {
          target.raw = `- ~~[${target.date}] ${target.text}~~ (Deprecated: ${proposal.content})`;
          target.deprecated = true;
          break;
        }
      }
      break;
    }
  }

  return serializeUserMd(doc);
}
