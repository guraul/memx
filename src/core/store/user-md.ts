import { readFileSync, writeFileSync, renameSync, mkdirSync, existsSync, readdirSync, unlinkSync } from "fs";
import { join, basename } from "path";
import { homedir } from "os";
import type { UserMdDoc, UserMdSection, UserMdEntry, StyleProposal } from "../types.ts";
import { CATEGORY_HEADERS, HEADER_TO_CATEGORY, CATEGORIES, type Category } from "../types.ts";
import { trimBlankLines, trimTrailingBlankLines } from "./markdown-lines.ts";

const ENTRY_REGEX = /^- (~~)?\[(\d{4}-\d{2}-\d{2})\]\s+(.+?)(~~)?(?:\s+\(Deprecated:.*\))?$/;

/** 由 serializeUserMd 每次重建的头部：解析时丢弃，否则每轮往返都会重复堆积 */
const GENERATED_HEADER = "# User Profile & Style";
const GENERATED_META_REGEX = /^> Auto-generated by opencode-memx\. Last updated: /;

export function getUserMdPath(): string {
  return join(homedir(), ".opencode", "USER.md");
}

function ensureDir(): void {
  const dir = join(homedir(), ".opencode");
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
  }
}

export function readUserMd(): string {
  const path = getUserMdPath();
  if (!existsSync(path)) {
    return "";
  }
  return readFileSync(path, "utf-8");
}

export function writeUserMd(content: string): void {
  ensureDir();
  const path = getUserMdPath();

  if (existsSync(path)) {
    backupUserMd();
    cleanupOldBackups(5);
  }

  const tmpPath = `${path}.tmp.${Date.now()}`;
  writeFileSync(tmpPath, content, "utf-8");
  renameSync(tmpPath, path);
}

/** 是否是我们自己生成的头部行（序列化时总会重建，解析时直接丢掉） */
function isGeneratedHeaderLine(line: string): boolean {
  return line === GENERATED_HEADER || GENERATED_META_REGEX.test(line);
}

/**
 * 解析 USER.md。受管集合 = 四个固定分类小节 + 其中的 `- [YYYY-MM-DD]` 条目；
 * 其余一切（用户自写的一级标题、散文、未知 ## 小节、小节里的非条目行、尾部内容）
 * 一律当作非受管内容原样带走，写回时不得丢失。
 */
export function parseUserMd(content: string): UserMdDoc {
  if (!content.trim()) {
    return {
      preamble: [],
      sections: CATEGORIES.map((cat) => ({
        header: CATEGORY_HEADERS[cat],
        category: cat,
        lines: [],
      })),
    };
  }

  const lines = content.split("\n");
  const preamble: string[] = [];
  const sections: UserMdSection[] = [];
  let current: UserMdSection | null = null;
  // 最近一个受管小节：受管区域内的非受管行（含未知 ## 小节）挂到它身上，
  // 这样未知小节不会跑到文件顶部被重排。
  let lastManaged: UserMdSection | null = null;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!;
    const headerMatch = line.match(/^## (.+)$/);

    if (headerMatch) {
      const header = headerMatch[1]!;
      const cat = HEADER_TO_CATEGORY[header];
      if (cat) {
        current = { header, category: cat, lines: [] };
        sections.push(current);
        lastManaged = current;
        continue;
      }
      // 未识别 ## 小节：整段按非受管内容保留，其后的条目行也不再归属上一个受管小节
      current = null;
    }

    const entryMatch = current ? line.match(ENTRY_REGEX) : null;
    if (entryMatch && current) {
      const date = entryMatch[2] ?? "";
      const text = entryMatch[3] ?? "";
      current.lines.push({
        raw: line,
        date,
        text,
        deprecated: !!entryMatch[1],
        lineNumber: i + 1,
      });
      continue;
    }

    if (current || lastManaged) {
      const owner = current ?? lastManaged!;
      owner.extras = [...(owner.extras ?? []), line];
    } else {
      preamble.push(line);
    }
  }

  return {
    // 我们自己生成的头部不带走（序列化会重建），否则往返会重复
    preamble: trimBlankLines(preamble.filter((l) => !isGeneratedHeaderLine(l))),
    sections,
  };
}

export function serializeUserMd(doc: UserMdDoc, lastUpdated?: string): string {
  const date = lastUpdated ?? new Date().toISOString().split("T")[0] ?? "";
  const result: string[] = [];

  // 非受管的前言排在生成头部之前，位置与原文一致
  if (doc.preamble.length > 0) {
    result.push(...doc.preamble, "");
  }

  result.push(GENERATED_HEADER, "", `> Auto-generated by opencode-memx. Last updated: ${date}`, "");

  for (const section of doc.sections) {
    const extras = trimTrailingBlankLines(section.extras ?? []);
    if (section.lines.length === 0 && extras.length === 0) continue;
    result.push(`## ${section.header}`);
    for (const entry of section.lines) {
      result.push(entry.raw);
    }
    result.push(...extras);
    result.push("");
  }

  return result.join("\n");
}

export function backupUserMd(): string | null {
  const path = getUserMdPath();
  if (!existsSync(path)) return null;
  const bakPath = `${path}.bak.${Date.now()}`;
  const content = readFileSync(path, "utf-8");
  writeFileSync(bakPath, content, "utf-8");
  return bakPath;
}

export function cleanupOldBackups(maxKeep = 5): void {
  const dir = join(homedir(), ".opencode");
  if (!existsSync(dir)) return;

  const prefix = `${basename(getUserMdPath())}.bak.`;
  const backups = readdirSync(dir)
    .filter((f) => f.startsWith(prefix))
    .map((f) => join(dir, f))
    .sort()
    .reverse();

  for (const old of backups.slice(maxKeep)) {
    try {
      unlinkSync(old);
    } catch {
      // ignore
    }
  }
}

export function isOverLimit(content: string, limit = 200): boolean {
  return content.split("\n").length > limit;
}

export interface ApplyResult {
  content: string;
  warnings: string[];
}

/** 内容锚点归一：去掉所有空白与常见 markdown 装饰再小写比较。
 *  LLM 抄写时多一个空格/星号不该丢掉锚，故 fuzzy 面比精确面宽。
 *
 *  ⚠️ 不变量：append 去重与 dedupeUserMd 必须复用本函数。若另写一套归一，
 *  "锚点认为相同"与"去重认为相同"就会分叉（改错条目 / 删错行）。 */
export function normalizeAnchor(text: string): string {
  return text
    .toLowerCase()
    .replace(/[`*_~]/g, "")
    .replace(/\s+/g, "")
    .replace(/[。，、；：！？.,;:!?]+$/g, "");
}

interface EntryHit {
  section: UserMdSection;
  index: number;
  /** exact=逐字 / fuzzy=归一后相等 / containment=包含 / line=行号兜底 */
  how: "exact" | "fuzzy" | "containment" | "line";
}

/**
 * P0-3(c) 内容锚点定位：优先 target_text（逐字 → 归一 → 唯一包含），最后才用 target_line。
 * 定位失败/降级都会写 warning（"为什么没改到我想改的那条"必须可见，不能静默）。
 */
function locateEntry(doc: UserMdDoc, proposal: StyleProposal, warnings: string[]): EntryHit | null {
  const hits: Array<{ section: UserMdSection; index: number; text: string }> = [];
  for (const section of doc.sections) {
    section.lines.forEach((entry, index) => hits.push({ section, index, text: entry.text }));
  }
  if (hits.length === 0) return null;

  const anchor = proposal.target_text?.trim();
  if (anchor) {
    const exact = hits.filter((h) => h.text.trim() === anchor);
    if (exact.length > 0) {
      if (exact.length > 1) warnings.push(`anchor 精确命中 ${exact.length} 条，取第一条`);
      return { section: exact[0]!.section, index: exact[0]!.index, how: "exact" };
    }
    const norm = normalizeAnchor(anchor);
    if (norm) {
      const fuzzy = hits.filter((h) => normalizeAnchor(h.text) === norm);
      if (fuzzy.length > 0) {
        if (fuzzy.length > 1) warnings.push(`anchor 归一命中 ${fuzzy.length} 条，取第一条`);
        warnings.push(`anchor 降级(fuzzy): "${anchor.slice(0, 40)}"`);
        return { section: fuzzy[0]!.section, index: fuzzy[0]!.index, how: "fuzzy" };
      }
      const contain = hits.filter((h) => {
        const t = normalizeAnchor(h.text);
        return norm.length > 0 && (t.includes(norm) || norm.includes(t));
      });
      if (contain.length === 1) {
        warnings.push(`anchor 降级(containment): "${anchor.slice(0, 40)}"`);
        return { section: contain[0]!.section, index: contain[0]!.index, how: "containment" };
      }
      if (contain.length > 1) {
        warnings.push(`anchor 包含命中 ${contain.length} 条，歧义 → 放弃内容锚点`);
      }
    }
  }

  if (proposal.target_line != null) {
    const byLine = hits.filter(
      (h) => h.section.lines[h.index]!.lineNumber === proposal.target_line,
    );
    if (byLine.length === 1) {
      warnings.push(`anchor 降级(行号兜底): target_line=${proposal.target_line}`);
      return { section: byLine[0]!.section, index: byLine[0]!.index, how: "line" };
    }
  }
  return null;
}

function applyOneProposal(doc: UserMdDoc, proposal: StyleProposal, today: string, warnings: string[]): void {
  const cat = proposal.category as Category;
  const header = CATEGORY_HEADERS[cat];

  let targetSection = doc.sections.find((s) => s.category === cat);
  if (!targetSection) {
    targetSection = { header, category: cat, lines: [] };
    doc.sections.push(targetSection);
  }

  const newRaw = `- [${today}] ${proposal.content}`;
  const newEntry: UserMdEntry = {
    raw: newRaw,
    date: today,
    text: proposal.content,
    deprecated: false,
    lineNumber: 0,
  };

  switch (proposal.action) {
    case "append": {
      // 去重与锚点归一复用同一套 normalizeAnchor（见其不变量注释）。
      // 查整个 doc 而非只查目标小节：同一批在内存 doc 上顺序应用，故同批重复也会被这里挡住。
      const anchor = normalizeAnchor(proposal.content);
      const duplicated = doc.sections.some((s) =>
        s.lines.some((e) => !e.deprecated && normalizeAnchor(e.text) === anchor),
      );
      if (anchor && duplicated) {
        warnings.push(`append 与既有条目重复 → 跳过: "${proposal.content.slice(0, 40)}"`);
        return;
      }
      targetSection.lines.push(newEntry);
      return;
    }
    case "update": {
      const located = locateEntry(doc, proposal, warnings);
      if (!located) {
        targetSection.lines.push(newEntry);
        warnings.push(`update 未定位到目标 → 追加为新条目: "${proposal.content.slice(0, 40)}"`);
        return;
      }
      located.section.lines[located.index] = newEntry;
      return;
    }
    case "deprecate": {
      const located = locateEntry(doc, proposal, warnings);
      if (!located) {
        warnings.push(`deprecate 未定位到目标 → 未改动: "${proposal.content.slice(0, 40)}"`);
        return;
      }
      const target = located.section.lines[located.index]!;
      if (target.deprecated) return;
      located.section.lines[located.index] = {
        ...target,
        raw: `- ~~[${target.date}] ${target.text}~~ (Deprecated: ${proposal.content})`,
        deprecated: true,
      };
      return;
    }
  }
}

/**
 * USER.md 写盘自愈（纯函数，可单测）：清掉两类历史重复。
 *  - deprecated 行与同小节有效条目同文 → 删（"重新记一次"留下的划掉旧行）
 *  - 同小节有效条目归一后同文 → 只留位置最早的那条，date 取该组最大值并同步重写 raw
 *
 * ⚠️ 两遍扫描：先扫完一个章节再判。边扫边判会在"划掉的行排在有效行之前"时漏删
 * （判到它时 active 集合还没建好）。
 */
export function dedupeUserMd(doc: UserMdDoc): { droppedDeprecated: number; mergedDuplicates: number } {
  let droppedDeprecated = 0;
  let mergedDuplicates = 0;

  for (const section of doc.sections) {
    const activeKeys = new Set<string>();
    for (const entry of section.lines) {
      if (!entry.deprecated) activeKeys.add(normalizeAnchor(entry.text));
    }
    section.lines = section.lines.filter((entry) => {
      if (entry.deprecated && activeKeys.has(normalizeAnchor(entry.text))) {
        droppedDeprecated++;
        return false;
      }
      return true;
    });
  }

  for (const section of doc.sections) {
    // 组内最新日期：ISO 字符串直接比大小，不依赖文件顺序
    const latestDate = new Map<string, string>();
    for (const entry of section.lines) {
      if (entry.deprecated) continue;
      const key = normalizeAnchor(entry.text);
      const prev = latestDate.get(key);
      if (prev === undefined || entry.date > prev) latestDate.set(key, entry.date);
    }

    const seen = new Set<string>();
    section.lines = section.lines.filter((entry) => {
      if (entry.deprecated) return true;
      const key = normalizeAnchor(entry.text);
      if (seen.has(key)) {
        mergedDuplicates++;
        return false;
      }
      seen.add(key);
      const date = latestDate.get(key);
      if (date !== undefined && date !== entry.date) {
        entry.date = date;
        entry.raw = `- [${date}] ${entry.text}`;
      }
      return true;
    });
  }

  return { droppedDeprecated, mergedDuplicates };
}

/**
 * P0-3(e) 单遍应用：parse 一次 → 内存中把整批 proposal 应用完 → serialize 一次。
 *
 * 旧实现每个 proposal 都独立 parse→修改→serialize 全文件，同批前面的 proposal 一旦改变了
 * 行结构（例如把空小节序列化掉导致行号前移），后面 proposal 手里那份快照行号就失效，
 * 结果是"改错行/丢改动"。单遍应用从根上消除批内漂移。
 */
export function applyProposals(proposals: StyleProposal[], content: string): ApplyResult {
  const doc = parseUserMd(content);
  const warnings: string[] = [];
  const today = new Date().toISOString().split("T")[0] ?? "";
  for (const proposal of proposals) {
    applyOneProposal(doc, proposal, today, warnings);
  }
  // 落盘前自愈历史重复（deprecate 分支不改：同一次写盘里由这里收口）
  const { droppedDeprecated, mergedDuplicates } = dedupeUserMd(doc);
  if (mergedDuplicates > 0) warnings.push(`自愈：合并 ${mergedDuplicates} 条重复条目`);
  if (droppedDeprecated > 0) warnings.push(`自愈：删除 ${droppedDeprecated} 条与有效条目同文的 deprecated 行`);
  return { content: serializeUserMd(doc), warnings };
}

/** 单条应用的兼容壳（内部仍走单遍实现） */
export function applyProposal(proposal: StyleProposal, content: string): string {
  return applyProposals([proposal], content).content;
}
