const SAMPLE = `# User Profile & Style

> Auto-generated by opencode-memx. Last updated: 2026-07-29

## 沟通与交互风格
- [2026-07-29] 偏好直接给出重构后的完整代码，而非分步骤解释
- [2026-07-28] 回答技术问题时先给结论，再展开推导过程

## 工具与环境偏好
- [2026-07-25] 使用 pnpm 而非 npm/yarn
- [2026-07-20] 编辑器为 Neovim，终端为 WezTerm

## 架构与技术决策
- [2026-07-22] 新项目默认使用 SvelteKit + Drizzle ORM

## 踩坑与禁忌
- [2026-07-27] 不要在代码注释中使用 Emoji
- ~~[2026-07-15] 偏好 Vue 3 Composition API~~ (Deprecated: 已迁移至 Svelte)
`;

describe("parseUserMd", () => {
  it("parses a complete USER.md into 4 sections", () => {
    const doc = parseUserMd(SAMPLE);
    expect(doc.sections).toHaveLength(4);
    expect(doc.preamble).toHaveLength(0);
  });

  it("parses communication section with 2 entries", () => {
    const doc = parseUserMd(SAMPLE);
    const comm = doc.sections.find((s) => s.category === "communication");
    expect(comm).toBeDefined();
    expect(comm!.lines).toHaveLength(2);
  });

  it("parses deprecated entry correctly", () => {
    const doc = parseUserMd(SAMPLE);
    const pitfall = doc.sections.find((s) => s.category === "pitfall");
    expect(pitfall).toBeDefined();
    const deprecated = pitfall!.lines.find((l) => l.deprecated);
    expect(deprecated).toBeDefined();
    expect(deprecated!.date).toBe("2026-07-15");
  });

  it("handles empty content gracefully", () => {
    const doc = parseUserMd("");
    expect(doc.sections).toHaveLength(4);
    expect(doc.preamble).toHaveLength(0);
    for (const s of doc.sections) {
      expect(s.lines).toHaveLength(0);
    }
  });

  it("preserves original line numbers", () => {
    const doc = parseUserMd(SAMPLE);
    const comm = doc.sections.find((s) => s.category === "communication")!;
    expect(comm.lines[0]!.lineNumber).toBe(6);
  });
});

describe("serializeUserMd", () => {
  it("produces valid markdown from parsed sections", () => {
    const serialized = serializeUserMd(parseUserMd(SAMPLE), "2026-07-29");
    expect(serialized).toContain("# User Profile & Style");
    expect(serialized).toContain("## 沟通与交互风格");
    expect(serialized).toContain("## 踩坑与禁忌");
  });

  it("includes last updated line", () => {
    const serialized = serializeUserMd(parseUserMd(SAMPLE), "2026-07-29");
    expect(serialized).toContain("2026-07-29");
  });
});

describe("isOverLimit", () => {
  it("returns false for content under limit", () => {
    expect(isOverLimit("line1\nline2\n", 10)).toBe(false);
  });

  it("returns true for content over limit", () => {
    const content = Array.from({ length: 250 }, (_, i) => `line ${i}`).join("\n");
    expect(isOverLimit(content, 200)).toBe(true);
  });
});

describe("applyProposal", () => {
  it("appends a new entry to the correct section", () => {
    const proposal: StyleProposal = {
      action: "append",
      category: "communication",
      content: "测试用偏好条目",
      reason: "测试",
    };
    const result = applyProposal(proposal, SAMPLE);
    expect(result).toContain("测试用偏好条目");
    expect(result).toContain("## 沟通与交互风格");
  });

  it("creates section if it does not exist", () => {
    const emptyDoc = `# User Profile & Style\n\n> Auto-generated by opencode-memx. Last updated: 2026-07-29\n`;
    const proposal: StyleProposal = {
      action: "append",
      category: "toolchain",
      content: "测试工具偏好",
      reason: "测试",
    };
    const result = applyProposal(proposal, emptyDoc);
    expect(result).toContain("## 工具与环境偏好");
    expect(result).toContain("测试工具偏好");
  });

  it("deprecates an existing entry by line number", () => {
    const doc = parseUserMd(SAMPLE);
    const pitfall = doc.sections.find((s) => s.category === "pitfall")!;
    const targetLine = pitfall.lines[0]!.lineNumber;

    const proposal: StyleProposal = {
      action: "deprecate",
      category: "pitfall",
      content: "不再适用",
      target_line: targetLine,
      reason: "测试废弃",
    };
    const result = applyProposal(proposal, SAMPLE);
    expect(result).toContain("~~");
    expect(result).toContain("(Deprecated: 不再适用)");
  });

  it("updates an existing entry by line number", () => {
    const doc = parseUserMd(SAMPLE);
    const comm = doc.sections.find((s) => s.category === "communication")!;
    const targetLine = comm.lines[0]!.lineNumber;

    const proposal: StyleProposal = {
      action: "update",
      category: "communication",
      content: "更新后的偏好",
      target_line: targetLine,
      reason: "测试更新",
    };
    const result = applyProposal(proposal, SAMPLE);
    expect(result).toContain("更新后的偏好");
  });
});

// #82 数据丢失回归：写盘只能改受管集合（四个固定 ## 小节 + 其中的条目行），
// 其余内容（自写一级标题、散文、未知 ## 小节、小节里的非条目行、尾部内容）必须原样留下。
// 真实现场：`<!-- memx:protocol -->` 协议块被抹掉后，AI 再也不会发 STYLE_SIGNAL，memx 静默停摆。
const MIXED = `# USER

<!-- memx:protocol -->
## Signal protocol (for the AI)
- Mark durable user preferences by emitting an HTML comment in your reply:
  \`<!-- STYLE_SIGNAL: {"category":"toolchain|communication","content":"<preference>"} -->\`
- The comment is machine-read (never shown to the user). One comment per preference.

# User Profile & Style

> Auto-generated by opencode-memx. Last updated: 2026-10-12

## 工具与环境偏好
- [2026-10-12] 使用 pnpm 作为包管理器
- 这是我自己加的一行说明，不是 memx 条目

## Notes
随手记的内容

## 沟通与交互风格
- [2026-10-12] 先给结论再给理由
`;

const PROTOCOL_MARKERS = [
  "# USER",
  "<!-- memx:protocol -->",
  "## Signal protocol (for the AI)",
  "Mark durable user preferences by emitting an HTML comment",
  "The comment is machine-read (never shown to the user)",
];

function expectUnmanagedIntact(content: string): void {
  for (const marker of PROTOCOL_MARKERS) {
    expect(content).toContain(marker);
  }
  // 小节内的非条目行、未知 ## 小节
  expect(content).toContain("- 这是我自己加的一行说明，不是 memx 条目");
  expect(content).toContain("## Notes");
  expect(content).toContain("随手记的内容");
}

describe("unmanaged content preservation", () => {
  it("keeps unmanaged content and adds the entry on append", () => {
    const result = applyProposal(
      { action: "append", category: "communication", content: "新增的沟通偏好", reason: "测试" },
      MIXED,
    );
    expectUnmanagedIntact(result);
    expect(result).toContain("- [2026-10-12] 使用 pnpm 作为包管理器");
    expect(result).toContain("新增的沟通偏好");
  });

  it("keeps unmanaged content on update", () => {
    const targetLine = parseUserMd(MIXED).sections
      .find((s) => s.category === "communication")!
      .lines[0]!.lineNumber;
    const result = applyProposal(
      {
        action: "update",
        category: "communication",
        content: "更新后的沟通偏好",
        target_line: targetLine,
        reason: "测试",
      },
      MIXED,
    );
    expectUnmanagedIntact(result);
    expect(result).toContain("更新后的沟通偏好");
    expect(result).not.toContain("- [2026-10-12] 先给结论再给理由");
  });

  it("keeps unmanaged content on deprecate", () => {
    const targetLine = parseUserMd(MIXED).sections
      .find((s) => s.category === "toolchain")!
      .lines[0]!.lineNumber;
    const result = applyProposal(
      {
        action: "deprecate",
        category: "toolchain",
        content: "不再适用",
        target_line: targetLine,
        reason: "测试",
      },
      MIXED,
    );
    expectUnmanagedIntact(result);
    expect(result).toContain("~~[2026-10-12] 使用 pnpm 作为包管理器~~");
    expect(result).toContain("(Deprecated: 不再适用)");
  });

  it("survives repeated writes without growing or duplicating", () => {
    const once = applyProposal(
      { action: "append", category: "pitfall", content: "踩坑偏好", reason: "测试" },
      MIXED,
    );
    const twice = applyProposal(
      { action: "append", category: "pitfall", content: "另一个踩坑偏好", reason: "测试" },
      once,
    );
    expectUnmanagedIntact(twice);
    expect(twice).toContain("踩坑偏好");
    expect(twice).toContain("另一个踩坑偏好");
    expect(twice.match(/# User Profile & Style/g)).toHaveLength(1);
    expect(twice.match(/memx:protocol/g)).toHaveLength(1);
  });

  it("serializeUserMd(parseUserMd(x)) is idempotent on a mixed file", () => {
    const first = serializeUserMd(parseUserMd(MIXED), "2026-10-12");
    const second = serializeUserMd(parseUserMd(first), "2026-10-12");
    expect(second).toBe(first);
    expectUnmanagedIntact(second);
    // 受管条目不丢不重不换序
    expect(second).toContain("使用 pnpm 作为包管理器");
    expect(second).toContain("先给结论再给理由");
    expect(second.match(/使用 pnpm 作为包管理器/g)).toHaveLength(1);
  });

  it("does not re-attribute entries under an unknown ## section", () => {
    // ## Notes 后面的条目行属于未识别小节，不能被吸进上一个受管小节
    const doc = parseUserMd(MIXED);
    const toolchain = doc.sections.find((s) => s.category === "toolchain")!;
    expect(toolchain.lines).toHaveLength(1);
    expect(toolchain.extras ?? []).toContain("## Notes");
  });

  it("whitespace-only input still produces the bare generated header", () => {
    const doc = parseUserMd("   \n\n  ");
    expect(doc.preamble).toHaveLength(0);
    const serialized = serializeUserMd(doc, "2026-10-12");
    expect(serialized).toBe(
      "# User Profile & Style\n\n> Auto-generated by opencode-memx. Last updated: 2026-10-12\n",
    );
  });
});

describe("readUserMd / writeUserMd", () => {
  const testContent = `# User Profile & Style\n\n> Auto-generated by opencode-memx. Last updated: 2026-07-29\n\n## 沟通与交互风格\n- [2026-07-29] 测试条目\n`;

  it("writes and reads back content", () => {
    writeUserMd(testContent);
    const read = readUserMd();
    expect(read).toContain("测试条目");
    expect(read).toContain("# User Profile & Style");
  });

  it("a refinement write over a hand-maintained file keeps it intact", () => {
    writeUserMd(MIXED);
    const next = applyProposal(
      { action: "append", category: "architecture", content: "写盘保留验证条目", reason: "测试" },
      readUserMd(),
    );
    writeUserMd(next);
    const read = readUserMd();
    expectUnmanagedIntact(read);
    expect(read).toContain("写盘保留验证条目");
    expect(read).toContain("使用 pnpm 作为包管理器");
  });
});

describe("backupUserMd", () => {
  it("creates a backup file", () => {
    const bakPath = backupUserMd();
    expect(bakPath).toBeTypeOf("string");
    expect(existsSync(bakPath!)).toBe(true);
    if (bakPath) unlinkSync(bakPath);
  });
});
