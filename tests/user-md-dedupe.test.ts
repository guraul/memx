// Track 1 写盘去重（append 守卫 + 落盘自愈 dedupeUserMd）回归。
// 全部走真实 applyProposals / dedupeUserMd —— 都是纯函数（不碰盘），故不 mock homedir。
import { describe, it, expect } from "vitest";
import { applyProposals, dedupeUserMd, parseUserMd } from "../src/core/store/user-md.ts";
import type { StyleProposal } from "../src/core/types.ts";

/** 造一份只含「工具与环境偏好」小节的 USER.md（条目行由调用方给出） */
const doc = (...lines: string[]): string =>
  `# User Profile & Style\n\n> Auto-generated by opencode-memx. Last updated: 2026-01-01\n\n## 工具与环境偏好\n${lines.join("\n")}\n`;

const append = (content: string): StyleProposal => ({
  action: "append",
  category: "toolchain",
  content,
  reason: "测试",
});

/** 只数有效（未被 ~~ 划掉）条目行 */
const activeLines = (content: string): string[] =>
  content.split("\n").filter((l) => /^- \[/.test(l));

describe("Track 1 写盘去重：append 守卫", () => {
  it("1) 同一批 4 次相同 append → 有效条目仅 1 条，且有「重复」告警", () => {
    const p = append("日志用 pino");
    const { content, warnings } = applyProposals([p, p, p, p], doc());
    expect(activeLines(content).filter((l) => l.includes("日志用 pino"))).toHaveLength(1);
    expect(warnings.some((w) => w.includes("append 与既有条目重复"))).toBe(true);
  });

  it("2) 跨轮：文件已有该条，再 append 同文本 → 仍 1 条", () => {
    const first = applyProposals([append("日志用 pino")], doc()).content;
    const { content, warnings } = applyProposals([append("日志用 pino")], first);
    expect(activeLines(content).filter((l) => l.includes("日志用 pino"))).toHaveLength(1);
    expect(warnings.some((w) => w.includes("append 与既有条目重复"))).toBe(true);
  });

  it("3) 归一化重复：尾标点/空格差异 → 合并为 1 条", () => {
    const { content } = applyProposals(
      [append("日志用 pino"), append("日志用 pino。"), append("日志 用 pino")],
      doc(),
    );
    expect(activeLines(content).filter((l) => l.includes("pino"))).toHaveLength(1);
  });
});

describe("Track 1 写盘去重：落盘自愈 dedupeUserMd", () => {
  it("4) deprecate(理由=自身文本) + append(同文本) → 只剩 1 条 active，无 ~~ 行", () => {
    const proposals: StyleProposal[] = [
      {
        action: "deprecate",
        category: "toolchain",
        content: "日志用 pino",
        target_text: "日志用 pino",
        reason: "重记",
      },
      append("日志用 pino"),
    ];
    const { content, warnings } = applyProposals(proposals, doc("- [2026-01-01] 日志用 pino"));
    expect(activeLines(content).filter((l) => l.includes("日志用 pino"))).toHaveLength(1);
    expect(content).not.toContain("~~");
    expect(warnings.join(" ")).toContain("自愈");
  });

  it("5) 顺序无关：deprecated 行排在 active 之前 → 同样被删", () => {
    const base = doc(
      "- ~~[2026-01-01] 日志用 pino~~ (Deprecated: 旧)",
      "- [2026-02-01] 日志用 pino",
    );
    const { content, warnings } = applyProposals([], base);
    expect(content).not.toContain("~~");
    expect(activeLines(content).filter((l) => l.includes("日志用 pino"))).toHaveLength(1);
    expect(warnings.join(" ")).toContain("自愈：删除 1 条");
  });

  it("6) 脏文件自愈：4 条相同 + 1 条仅差尾标点，喂空提案 → 收敛 1 条且日期取组内最新", () => {
    const dirty = doc(
      "- [2026-01-01] 日志用 pino",
      "- [2026-02-02] 日志用 pino",
      "- [2026-03-03] 日志用 pino",
      "- [2026-04-04] 日志用 pino",
      "- [2026-05-05] 日志用 pino。",
    );
    const { content, warnings } = applyProposals([], dirty);
    const pinoLines = activeLines(content).filter((l) => l.includes("pino"));
    expect(pinoLines).toHaveLength(1);
    // 位置最早的那条被保留，date 取组内最大（ISO 字符串直接比大小）
    expect(pinoLines[0]).toBe("- [2026-05-05] 日志用 pino");
    expect(warnings.join(" ")).toContain("自愈：合并 4 条重复条目");
    // 纯函数接口同源：直接跑一遍给出同样的计数
    expect(dedupeUserMd(parseUserMd(dirty))).toEqual({ droppedDeprecated: 0, mergedDuplicates: 4 });
  });

  it("7) 幂等：对自愈后的内容再 applyProposals([]) 不再变化，warnings 不含「自愈」", () => {
    const healed = applyProposals(
      [],
      doc("- [2026-01-01] 日志用 pino", "- [2026-05-05] 日志用 pino。"),
    ).content;
    const again = applyProposals([], healed);
    expect(again.content).toBe(healed);
    expect(again.warnings.join(" ")).not.toContain("自愈");
  });

  it("8) 边界：不同文本不误删；deprecated 条目不算「既有条目」", () => {
    // (a) 不同文本：两条 append 各自与既有条目重复 → 都被守卫挡住，两条都在
    const two = doc("- [2026-01-01] 日志用 pino", "- [2026-01-02] 日志用 winston");
    const r1 = applyProposals([append("日志用 pino"), append("日志用 winston")], two);
    expect(activeLines(r1.content).filter((l) => l.includes("日志用"))).toHaveLength(2);
    expect(r1.warnings.filter((w) => w.includes("重复"))).toHaveLength(2);

    // (b) 已 deprecated 的同文本条目不算既有 → append 不被守卫挡住，随后自愈收口为 1 条 active
    const dep = doc("- ~~[2026-01-01] 日志用 pino~~ (Deprecated: 换工具)");
    const r2 = applyProposals([append("日志用 pino")], dep);
    expect(activeLines(r2.content)).toHaveLength(1);
    expect(r2.warnings.some((w) => w.includes("append 与既有条目重复"))).toBe(false);
    expect(r2.content).not.toContain("~~");
  });
});
